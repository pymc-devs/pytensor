@register_jitable
def polynomial(x, coefficients):
    result = coefficients[0]
    for coefficient in coefficients[1:]:
        result = result * x + coefficient
    return result


@register_jitable(inline="always")
def positive_psi(x):
    x = float(x)
    result = 0.0
    if x <= 10 and x == math.floor(x):
        for k in range(1, int(x)):
            result += 1.0 / k
        return result - 0.577215664901532860606512090082402431
    if x < 1:
        result -= 1 / x
        x += 1
    elif x < 10:
        while x > 2:
            x -= 1
            result += 1 / x
    if x <= 2:
        # Three-part root preserves accuracy where digamma crosses zero.
        gap = x - 1569415565.0 / 1073741824.0
        gap -= (381566830.0 / 1073741824.0) / 1073741824.0
        gap -= 0.9016312093258695918615325266959189453125e-19
        ratio = polynomial(x - 1, PSI_P) / polynomial(x - 1, PSI_Q)
        return result + gap * 0.99558162689208984 + gap * ratio
    correction = 0.0
    if x < 1e17:
        inverse_square = 1 / (x * x)
        correction = inverse_square * polynomial(inverse_square, PSI_A)
    return result + math.log(x) - 0.5 / x - correction


