@register_jitable(inline="always")
def positive_loggamma(x):
    x = float(x)
    if x < 13:
        product, shift, shifted = 1.0, 0.0, x
        while shifted >= 3:
            shift -= 1
            shifted = x + shift
            product *= shifted
        while shifted < 2:
            product /= shifted
            shift += 1
            shifted = x + shift
        if shifted == 2:
            return math.log(product)
        argument = x + shift - 2
        correction = (
            argument * polynomial(argument, GAMMA_B) / polynomial(argument, GAMMA_C)
        )
        return math.log(product) + correction
    result = (x - 0.5) * math.log(x) - x + 0.91893853320467274178
    if x > 1e8:
        return result
    inverse_square = 1 / (x * x)
    if x >= 1000:
        correction = (
            (7.9365079365079365079365e-4 * inverse_square - 2.7777777777777777777778e-3)
            * inverse_square
            + 1 / 12
        ) / x
    else:
        correction = polynomial(inverse_square, GAMMA_A) / x
    return result + correction
